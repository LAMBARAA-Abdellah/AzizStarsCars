function initApp() {
    return {
        lang: localStorage.getItem('lang') || 'fr',
        theme: localStorage.getItem('theme') || 'dark',
        mobileMenu: false,
        scrolled: false,
        activeFilter: 'all',
        cars: carData,
        phone: "+212665660104",
        phoneFormatted: "+212 665-660104",
        t(key) {
            return translations[this.lang][key] || key;
        },
        toggleTheme() {
            this.theme = this.theme === 'dark' ? 'light' : 'dark';
            localStorage.setItem('theme', this.theme);
        },
        setLang(l) {
            this.lang = l;
            localStorage.setItem('lang', l);
            document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
            document.documentElement.lang = l;
            // Re-initialize AOS on language change for better RTL experience
            setTimeout(() => AOS.refresh(), 100);
        },
        init() {
            this.setLang(this.lang);
            AOS.init({ duration: 1000, once: true });
            lucide.createIcons();
            window.addEventListener('scroll', () => {
                this.scrolled = window.pageYOffset > 50;
            });
        },
        async hdSend(event) {
            event.preventDefault();
            const form = event.target;
            const btn = form.querySelector('button[type="submit"]');
            const originalBtnText = btn.innerText;

            // Loading state
            btn.disabled = true;
            btn.innerHTML = `<span class="spinner-border spinner-border-sm" role="status" aria-hidden="true"></span> ${this.t('btn_sending')}`;

            const formData = new FormData(form);

            try {
                const response = await fetch(form.action, {
                    method: 'POST',
                    body: formData,
                    headers: {
                        'Accept': 'application/json'
                    }
                });

                if (response.ok) {
                    Swal.fire({
                        icon: 'success',
                        title: this.t('msg_success_title'),
                        text: this.t('msg_success_text'),
                        confirmButtonColor: '#D4AF37'
                    });
                    form.reset();
                } else {
                    throw new Error('Form submission failed');
                }
            } catch (error) {
                Swal.fire({
                    icon: 'error',
                    title: this.t('msg_error_title'),
                    text: this.t('msg_error_text'),
                    confirmButtonColor: '#D4AF37'
                });
            } finally {
                btn.disabled = false;
                btn.innerText = originalBtnText;
            }
        }
    }
}


